func UniqueName(t testing.TB, prefix string) string {
	t.Helper()

	randomBytes := make([]byte, 4)
	if _, err := rand.Read(randomBytes); err != nil {
		t.Fatalf("generate random bytes failed: %v", err)
	}

	return fmt.Sprintf("%s_%s", prefix, hex.EncodeToString(randomBytes))
}

func assertTestDatabase(t testing.TB, db *gorm.DB) {
	t.Helper()

	var databaseName string
	if err := db.Raw("SELECT current_database()").Scan(&databaseName).Error; err != nil {
		t.Fatalf("read current database failed: %v", err)
	}

	if !strings.Contains(strings.ToLower(databaseName), "test") {
		t.Fatalf("refusing to run integration tests on non-test database %q", databaseName)
	}
}

// acquireIntegrationLock 用 PG 的 advisory lock 替代 MySQL 的 GET_LOCK。
//
// ⚠️ 两者的**返回值语义不同**（这正是 ADR §3 点名的那条）：
//
//	MySQL `GET_LOCK(name, 30)` 返回 1（拿到）/ 0（超时）/ NULL（出错）
//	PG    `pg_try_advisory_lock(key)` 返回 **boolean**，且**不等待**
//
// ⇒ 不能照抄 `if lockResult != 1`（那样 PG 下永远为真，判据死掉）。
// 这里用 `pg_try_advisory_lock` + 显式重试，保留原 SQL 的「最多等 30 秒」语义。
func acquireIntegrationLock(t testing.TB, db *gorm.DB) {
	t.Helper()

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	// hashtext 把名字稳定映射为 int4；与常量锁 key 等价，但可读。
	const query = `SELECT pg_try_advisory_lock(hashtext(?))`

	deadline := time.Now().Add(30 * time.Second)
	for {
		var acquired bool
		if err := db.WithContext(ctx).Raw(query, integrationAdvisoryLockKey).Scan(&acquired).Error; err != nil {
			t.Fatalf("acquire postgres integration lock failed: %v", err)
		}
		if acquired {
			return
		}
		if time.Now().After(deadline) {
			t.Fatalf("acquire postgres integration lock timed out")
		}
		time.Sleep(100 * time.Millisecond)
	}
}

// quoteIdentifier 用 PG 的双引号（原 MySQL 版用反引号）。
func quoteIdentifier(t testing.TB, identifier string) string {
	t.Helper()

	if identifier == "" {
		t.Fatal("empty sql identifier")
	}

	for _, character := range identifier {
		if character == '_' || unicode.IsLetter(character) || unicode.IsDigit(character) {
			continue
		}
		t.Fatalf("invalid sql identifier %q", identifier)
	}

	return `"` + identifier + `"`
}
