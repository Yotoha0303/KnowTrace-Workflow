var openPostgresDB = func(dsn string) (*gorm.DB, error) {
	return gorm.Open(postgres.Open(dsn), &gorm.Config{
		Logger: logger.Default.LogMode(logger.Silent),
	})
}

// OpenTestDB 打开测试库。函数名由 OpenMySQL 改为 OpenTestDB —— 库已不是 MySQL，
// 保留旧名会让读者以为驱动仍是 mysql。
func OpenTestDB(t testing.TB) *gorm.DB {
	t.Helper()

	dsn := strings.TrimSpace(os.Getenv(TestDatabaseDSNEnv))
	if dsn == "" {
		t.Skipf("set %s to run PostgreSQL integration tests", TestDatabaseDSNEnv)
	}

	db, err := openPostgresDB(dsn)
	if err != nil {
		t.Fatalf("open test postgres failed: %v", err)
	}

	sqlDB, err := db.DB()
	if err != nil {
		t.Fatalf("get sql db failed: %v", err)
	}
	sqlDB.SetMaxOpenConns(1)
	sqlDB.SetMaxIdleConns(1)

	assertTestDatabase(t, db)
	acquireIntegrationLock(t, db)

	// 必须在返回前打印：调用方拿到的 db 已经过 assertTestDatabase 的「库名含 test」检查
	// 与 advisory lock，此时若能答出 current_database()/server_version，就是一条真实连接。
	emitRealDBFingerprint(t, db)

	return db
}

// emitRealDBFingerprint 打印一行可被 CI 断言步 grep 的标记，证明 db 背后是真实 PostgreSQL。
//
// 失败时**只用 t.Log，绝不 t.Fatalf**：postgres_test.go 里有多条用例把 openPostgresDB 指向
// fake driver 并照常调用 OpenTestDB。若这里 Fatal，那些单元测会红，而它们的 red
// 与「指纹没打出来」混在一起，反而让门更难诊断。
// **假连接不会因此蒙混过关**：buildRealDBFingerprint 拿不到合法值就返回空串，
// 标记不会出现，断言步照样红。
func emitRealDBFingerprint(t testing.TB, db *gorm.DB) {
	t.Helper()

	marker, err := buildRealDBFingerprint(db)
	if err != nil {
		t.Logf("could not build the real-db fingerprint: %v", err)
		return
	}
	if marker == "" {
		t.Log("not emitting a real-db fingerprint: the connection does not answer like a real PostgreSQL")
		return
	}

	// 走 testing 的日志而非 os.Stdout：`go test -json` 会把它包成一条 Output 事件，
	// CI 用同一个 `go test -json | tee` 就同时拿到 PASS 计数与指纹。
	t.Log(marker)
}

// buildRealDBFingerprint 向数据库要 current_database() 与 server_version，拼成可 grep 的标记。
// 返回空串表示「这条连接答不出真实 PostgreSQL 的答案」，调用方不得打印标记。
func buildRealDBFingerprint(db *gorm.DB) (string, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()

	var databaseName string
	if err := db.WithContext(ctx).Raw("SELECT current_database()").Scan(&databaseName).Error; err != nil {
		return "", fmt.Errorf("read current_database(): %w", err)
	}

	var serverVersion string
	if err := db.WithContext(ctx).Raw("SELECT current_setting('server_version')").Scan(&serverVersion).Error; err != nil {
		return "", fmt.Errorf("read server_version: %w", err)
	}

	if !isRealDBFingerprint(databaseName, serverVersion) {
		return "", nil
	}

	return RealDBFingerprintPrefix + "database=" + databaseName + " version=" + serverVersion, nil
}

// isRealDBFingerprint 是标记的准入判据：库名非空 + 版本号形如 x.y 或 x.y.z。
//
// PG 的 server_version 形如 `17.11`（**两段**），而 MySQL 是 `8.0.36`（三段）——
// 因此正则必须接受 2~4 段，不能照抄 MySQL 的 `^\d+\.\d+\.\d+`（那样真实 PG 会被误拒）。
func isRealDBFingerprint(databaseName, serverVersion string) bool {
	if strings.TrimSpace(databaseName) == "" {
		return false
	}
	return pgServerVersionPattern.MatchString(strings.TrimSpace(serverVersion))
}

func CloseTestDB(t testing.TB, db *gorm.DB) {
	t.Helper()

	if db == nil {
		return
	}

	sqlDB, err := db.DB()
	if err != nil {
		t.Fatalf("get sql db failed: %v", err)
	}
	if err := sqlDB.Close(); err != nil {
		t.Fatalf("close sql db failed: %v", err)
	}
}

// ResetTables 删除给定表。
//
// 原 MySQL 版会 `SET FOREIGN_KEY_CHECKS = 0/1` 再逐表 DROP。**PG 版直接删掉那两句**：
// 实测 migrations/ 与 testutil 的建表语句里**没有任何外键**（`grep REFERENCES` = 0），
// 而 PG 的等价物（`SET session_replication_role = replica`）需要超级用户，
// 测试账户用不了。**这不削弱判据**——没有外键就没有要绕过的检查。
func ResetTables(t testing.TB, db *gorm.DB, tableNames ...string) {
	t.Helper()

	if len(tableNames) == 0 {
		return
	}

	for _, tableName := range tableNames {
		if err := db.Exec(fmt.Sprintf("DROP TABLE IF EXISTS %s", quoteIdentifier(t, tableName))).Error; err != nil {
			t.Fatalf("drop table %s failed: %v", tableName, err)
		}
	}
}

