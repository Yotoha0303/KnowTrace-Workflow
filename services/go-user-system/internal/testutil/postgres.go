// 本文件原为 MySQL 版（internal/testutil/mysql.go）。M3（ADR-0019）整体改为 PG。
//
// 五处 MySQL 专有 SQL 的替换（逐条实测，非推断）：
//   SELECT DATABASE()          → SELECT current_database()
//   SELECT VERSION()           → SELECT current_setting('server_version')
//   GET_LOCK(name, 30)         → pg_try_advisory_lock(hashtext(name))
//   SET FOREIGN_KEY_CHECKS=0/1 → **直接删除**（本 schema 无外键，实测 migrations/ 里 0 处 REFERENCES）
//   AUTO_INCREMENT/TINYINT/DATETIME(3)/ENGINE=/utf8mb4/UNIQUE KEY/KEY
//                              → PG 同义语法（见各建表常量）

const TestDatabaseDSNEnv = "TEST_DATABASE_DSN"
const integrationAdvisoryLockKey = "go_user_system_integration_tests"

// RealDBFingerprintPrefix 是「本测试二进制确实连上过真实 PostgreSQL」的日志标记前缀。
//
// CI 的断言步（scripts/check-go-integration-gate.mjs）grep 它，用来堵住
// 「集成测被换成 fake driver，却照样 PASS」这条假绿路径——fake driver
// （postgres_test.go 的 testutilSQLDriver）不经过这里，也就产不出这一行。
//
// ⚠️ **它是跳线（tripwire），不是证据（proof）**：任何测试都能一行 t.Log 伪造。
// 真正作证的是服务端门（scripts/check-go-integration-server-witness.mjs）。
const RealDBFingerprintPrefix = "REAL_DB_FINGERPRINT "

// pgServerVersionPattern 接受 PG 的 server_version：`17.11`（两段），也容忍 `17.11.0`。
// ⚠️ 不能照抄 MySQL 的 `^\d+\.\d+\.\d+`——真实 PG 输出是**两段**，那样会被误拒。
var pgServerVersionPattern = regexp.MustCompile(`^\d+\.\d+(\.\d+)?`)

