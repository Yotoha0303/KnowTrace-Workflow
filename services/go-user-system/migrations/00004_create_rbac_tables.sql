-- PostgreSQL 方言。三处不是机械替换：
--   1) `INSERT ... ON DUPLICATE KEY UPDATE x = VALUES(x)` → `ON CONFLICT ... DO UPDATE SET x = excluded.x`
--   2) `INSERT IGNORE ... SELECT ... JOIN ... WHERE` → `ON CONFLICT DO NOTHING`
--      ⚠️ 原 SQL 是 `JOIN permissions p WHERE r.code='user' AND p.code IN (...)`——
--         **没有 ON 子句的 CROSS JOIN**。PG 里必须显式写 `CROSS JOIN`，否则是语法错误。
--   3) `NOW(3)` → `now()`
CREATE TABLE IF NOT EXISTS roles (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    code varchar(64) NOT NULL,
    name varchar(64) NOT NULL,
    created_at timestamptz(3) NULL DEFAULT NULL,
    updated_at timestamptz(3) NULL DEFAULT NULL,
    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_roles_code ON roles (lower(code));

CREATE TABLE IF NOT EXISTS permissions (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    code varchar(128) NOT NULL,
    name varchar(64) NOT NULL,
    method varchar(16) NOT NULL,
    path varchar(255) NOT NULL,
    created_at timestamptz(3) NULL DEFAULT NULL,
    updated_at timestamptz(3) NULL DEFAULT NULL,
    PRIMARY KEY (id)
);
CREATE UNIQUE INDEX IF NOT EXISTS uk_permissions_code ON permissions (lower(code));
CREATE UNIQUE INDEX IF NOT EXISTS uk_permissions_method_path ON permissions (method, path);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id bigint NOT NULL,
    role_id bigint NOT NULL,
    created_at timestamptz(3) NULL DEFAULT NULL,
    PRIMARY KEY (user_id, role_id)
);
CREATE INDEX IF NOT EXISTS idx_user_roles_role_id ON user_roles (role_id);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id bigint NOT NULL,
    permission_id bigint NOT NULL,
    created_at timestamptz(3) NULL DEFAULT NULL,
    PRIMARY KEY (role_id, permission_id)
);
CREATE INDEX IF NOT EXISTS idx_role_permissions_permission_id ON role_permissions (permission_id);

