-- create users table
-- PostgreSQL 方言（ADR-0019 §2）：AUTO_INCREMENT → IDENTITY；TINYINT → smallint；
-- DATETIME(3) → timestamptz(3)；utf8mb4/COLLATE 删除（库级）；唯一键改表达式索引 lower()。
CREATE TABLE IF NOT EXISTS users (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    username varchar(64) NOT NULL,
    password_hash varchar(255) NOT NULL,
    nickname varchar(64) NOT NULL DEFAULT '',
    status smallint NOT NULL DEFAULT 1,
    created_at timestamptz(3) NULL DEFAULT NULL,
    updated_at timestamptz(3) NULL DEFAULT NULL,
    PRIMARY KEY (id)
);

-- ADR-0019 §5.3 M7：原 MySQL 为 utf8mb4_0900_ai_ci（大小写不敏感），
-- PG 默认大小写敏感 ⇒ 用表达式索引保住原语义（Alice 与 alice 仍冲突）。
CREATE UNIQUE INDEX IF NOT EXISTS idx_username ON users (lower(username));

