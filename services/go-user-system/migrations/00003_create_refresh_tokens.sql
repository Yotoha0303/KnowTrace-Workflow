-- UNIQUE KEY/KEY → CREATE INDEX；utf8mb4/COLLATE 删除。
CREATE TABLE IF NOT EXISTS refresh_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    user_id bigint NOT NULL,
    jti varchar(64) NOT NULL,
    token_hash char(64) NOT NULL,
    expires_at timestamptz(3) NOT NULL,
    revoked_at timestamptz(3) NULL DEFAULT NULL,
    replaced_by_jti varchar(64) NULL DEFAULT NULL,
    created_at timestamptz(3) NULL DEFAULT NULL,
    updated_at timestamptz(3) NULL DEFAULT NULL,
    PRIMARY KEY (id)
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_refresh_tokens_jti ON refresh_tokens (jti);
CREATE UNIQUE INDEX IF NOT EXISTS uk_refresh_tokens_hash ON refresh_tokens (token_hash);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id ON refresh_tokens (user_id);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expires_at ON refresh_tokens (expires_at);

